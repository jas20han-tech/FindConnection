from app.reasoning.path_finder import PathResult
from app.reasoning.temporal import temporal_diff
from app.schemas.graph import Community, GraphEdge, GraphNode
from app.schemas.impact import ImpactResult
from app.schemas.query import Citation
from app.schemas.types import QueryMode

logger = logging.getLogger(__name__)

CITATION_RE = re.compile(r"\[\[([a-zA-Z0-9_\-]+)\]\]")

VERB_PHRASES: dict[str, str] = {
    "CEO_OF": "serves as chief executive of",
    "DEVELOPED": "developed",
    "INVESTED_IN": "invested in",
    "ACQUIRED": "acquired",
    "SUPPLIES": "supplies",
    "REGULATES": "regulates",
    "REGULATED_BY": "is regulated by",
    "PARTNERED_WITH": "partnered with",
    "COMPETES_WITH": "competes with",
    "FOUNDED": "founded",
    "PUBLISHED": "published",
    "OWNS": "owns",
    "HOSTS": "hosts",
    "USES": "uses",
    "BUILT_ON": "is built on",
    "TRAINED": "was used to train",
    "MANUFACTURES": "manufactures",
    "RESTRICTS": "restricts",
    "EVALUATES": "evaluates",
    "INVESTIGATES": "investigates",
    "ALTERNATIVE_TO": "is an alternative to",
    "REFERENCES": "references",
    "SUSPENDED": "suspended",
}


@dataclass(slots=True)
class SynthesisContext:
    query: str
    mode: QueryMode
    nodes: list[GraphNode]
    edges: list[GraphEdge]
    communities: list[Community] = field(default_factory=list)
    highlighted_node_ids: list[str] = field(default_factory=list)
    highlighted_edge_ids: list[str] = field(default_factory=list)
    path: PathResult | None = None
    scores: dict[str, float] = field(default_factory=dict)
    impact: ImpactResult | None = None
    year: int | None = None
    confidence: float = 0.5

    @property
    def node_map(self) -> dict[str, GraphNode]:
        return {node.id: node for node in self.nodes}

    @property
    def edge_map(self) -> dict[str, GraphEdge]:
        return {edge.id: edge for edge in self.edges}

    def relevant_edges(self, limit: int = 12) -> list[GraphEdge]:
        edge_map = self.edge_map
        ordered: list[GraphEdge] = []
        seen: set[str] = set()
        for edge_id in [*(self.path.edge_ids if self.path else []), *self.highlighted_edge_ids]:
            edge = edge_map.get(edge_id)
            if edge and edge.id not in seen:
                seen.add(edge.id)
                ordered.append(edge)
        if not ordered:
            candidates = [edge for edge in self.edges if edge.status != "DISSOLVED"]
            candidates.sort(key=lambda edge: edge.strength, reverse=True)
            ordered = candidates[:limit]
        return ordered[: limit * 2]

    def citations(self) -> list[Citation]:
        node_map = self.node_map
        citations: list[Citation] = []
        seen: set[str] = set()
        for edge in self.relevant_edges():
            if edge.id in seen:
                continue
            seen.add(edge.id)
            source = node_map.get(edge.source)
            target = node_map.get(edge.target)
            label = (
                f"{source.name if source else edge.source} → "
                f"{target.name if target else edge.target}"
            )
            citations.append(
                Citation(
                    edge_id=edge.id,
                    label=label,
                    document=edge.source_doc or "Seed knowledge graph",
                    page=edge.source_page,
                    chunk_id=edge.source_chunk_id,
                    date=edge.date,
                )
            )
        return citations


def confidence_for(
    *,
    seeds: list[str],
    path: PathResult | None,
    citations: int,
    mode: QueryMode,
) -> float:
    score = 0.42
    if seeds:
        score += 0.18
    if len(seeds) >= 2:
        score += 0.08
    if path is not None:
        score += 0.16 if path.found else 0.02
    score += min(0.12, citations * 0.015)
    if mode in {"CONNECTION", "IMPACT"}:
        score += 0.03
    return round(min(0.98, max(0.35, score)), 3)


# --------------------------------------------------------------------------- local narrative
def _verb(edge: GraphEdge) -> str:
    return VERB_PHRASES.get(edge.type, f"is linked to via {edge.type.lower().replace('_', ' ')}")


def _date_suffix(edge: GraphEdge) -> str:
    return f" ({edge.year})" if edge.year else ""


def fallback_narrative(context: SynthesisContext) -> str:
    node_map = context.node_map
    edge_map = context.edge_map

    if context.mode == "CONNECTION":
        return _connection_narrative(context, node_map, edge_map)
    if context.mode == "IMPACT":
        return _impact_narrative(context, node_map)
    if context.mode == "TEMPORAL":
        return _temporal_narrative(context, node_map)
    return _global_narrative(context, node_map)


def _connection_narrative(
    context: SynthesisContext,
    node_map: dict[str, GraphNode],
    edge_map: dict[str, GraphEdge],
) -> str:
    path = context.path
    if path and path.found and path.edge_ids:
        start = node_map.get(path.node_ids[0])
        end = node_map.get(path.node_ids[-1])
        lines = [
            f"**{start.name if start else path.node_ids[0]}** reaches "
            f"**{end.name if end else path.node_ids[-1]}** through a "
            f"{path.hops}-hop verified route in the knowledge graph.\n"
        ]
        for index, edge_id in enumerate(path.edge_ids):
            edge = edge_map.get(edge_id)
            if not edge:
                continue
            source = node_map.get(path.node_ids[index])
            target = node_map.get(path.node_ids[index + 1])
            lines.append(
                f"- **{source.name if source else edge.source}** {_verb(edge)} "
                f"**{target.name if target else edge.target}**{_date_suffix(edge)}. "
                f"{edge.description} [[{edge.id}]]"
            )
        strongest = max(
            (edge_map[eid] for eid in path.edge_ids if eid in edge_map),
            key=lambda edge: edge.strength,
            default=None,
        )
        if strongest:
            source = node_map.get(strongest.source)
            target = node_map.get(strongest.target)
            lines.append(
                f"\nThe strongest link is **{source.name if source else strongest.source} → "
                f"{target.name if target else strongest.target}** "
                f"({strongest.type}, strength {strongest.strength}/10), supported by "
                f"`{strongest.source_doc or 'the source corpus'}`"
                + (f", page {strongest.source_page}" if strongest.source_page else "")
                + "."
            )
        return "\n".join(lines)

    seeds = [node_map[node_id] for node_id in context.highlighted_node_ids if node_id in node_map]
    if not seeds:
        return (
            "No named entity in the graph matched this query strongly enough to anchor a path. "
            "Try an `@Entity` mention or ask about a specific organization, model or regulation."
        )
    seed = seeds[0]
    neighbours = [
        edge
        for edge in context.edges
        if edge.status != "DISSOLVED" and seed.id in (edge.source, edge.target)
    ]
    neighbours.sort(key=lambda edge: edge.strength, reverse=True)
    lines = [
        "No complete route was found within 5 hops. "
        f"**{seed.name}** sits in a cluster with {seed.degree} direct relationship(s).\n"
    ]
    for edge in neighbours[:6]:
        other_id = edge.target if edge.source == seed.id else edge.source
        other = node_map.get(other_id)
        lines.append(
            f"- **{seed.name}** {_verb(edge)} **{other.name if other else other_id}**"
            f"{_date_suffix(edge)}. {edge.description} [[{edge.id}]]"
        )
    return "\n".join(lines)


def _impact_narrative(context: SynthesisContext, node_map: dict[str, GraphNode]) -> str:
    impact = context.impact
    if impact is None:
        return "Impact simulation did not return a result for this entity."
    removed = impact.removed_node.get("name", impact.removed_node.get("id", "the entity"))
    lines = [
        f"Severing **{removed}** produces **{impact.severity}** structural risk "
        f"({impact.risk_score * 100:.0f}/100) across {len(impact.directly_disrupted)} direct "
        f"dependenc{'y' if len(impact.directly_disrupted) == 1 else 'ies'}.\n"
    ]
    if impact.severed_edges:
        lines.append(
            f"{len(impact.severed_edges)} relationship(s) are severed and the connected-component "
            f"count moves from {impact.component_count_before} to {impact.component_count_after}."
        )
    if impact.orphaned:
        names = ", ".join(node.name for node in impact.orphaned[:6])
        lines.append(
            f"\n**Orphaned entities (degree → 0):** {names}. These nodes lose every grounded link "
            "and would drop out of retrieval until reconnected."
        )
    else:
        lines.append(
            "\nNo neighbour is fully orphaned: every dependent retains at least one alternative "
            "path, which limits cascade depth."
        )
    if impact.centrality_surge:
        lines.append("\n**Centrality surge among surviving hubs:**")
        for surge in impact.centrality_surge[:4]:
            lines.append(
                f"- **{surge.name}** absorbs +{surge.delta_pct:.0f}% betweenness "
                f"({surge.baseline:.4f} → {surge.projected:.4f})."
            )
    lines.append(
        f"\nLargest remaining component holds {impact.largest_component_ratio_after * 100:.0f}% "
        f"of nodes; disruption ratio is {impact.disruption_ratio * 100:.0f}%. "
        f"Simulation completed in {impact.duration_ms:.1f} ms without touching the database."
    )
    return "\n".join(lines)


def _temporal_narrative(context: SynthesisContext, node_map: dict[str, GraphNode]) -> str:
    year = context.year or 2024
    diff = temporal_diff(context.edges, year)
    lines = [
        f"At the **{year}** time slice, {diff.active_edges} relationship(s) are active across "
        f"{len({e.source for e in context.edges if e.year is None or e.year <= year})} entities.\n"
    ]
    new_edges = [edge for edge in context.edges if edge.id in diff.new_edge_ids]
    if new_edges:
        lines.append(f"**Introduced in {year}:**")
        for edge in sorted(new_edges, key=lambda item: item.strength, reverse=True)[:8]:
            source = node_map.get(edge.source)
            target = node_map.get(edge.target)
            lines.append(
                f"- **{source.name if source else edge.source}** {_verb(edge)} "
                f"**{target.name if target else edge.target}**. {edge.description} [[{edge.id}]]"
            )
    dissolved = [edge for edge in context.edges if edge.id in diff.dissolved_edge_ids]
    if dissolved:
        lines.append(f"\n**Dissolved in {year}:**")
        for edge in dissolved[:5]:
            lines.append(f"- {edge.description} [[{edge.id}]]")
    if diff.edges_by_year:
        timeline = ", ".join(f"{year}: {count}" for year, count in diff.edges_by_year.items())
        lines.append(f"\n**Edge creation timeline:** {timeline}.")
    return "\n".join(lines)


def _global_narrative(context: SynthesisContext, node_map: dict[str, GraphNode]) -> str:
    overview = community_overview(context.nodes, context.edges, context.communities)
    hubs = sorted(context.nodes, key=lambda node: (node.pagerank, node.degree), reverse=True)[:6]
    lines = [
        f"The graph currently holds **{len(context.nodes)} entities** and "
        f"**{len(context.edges)} relationships** across {len(overview)} detected communities.\n"
    ]
    if hubs:
        lines.append(
            "**Structural hubs:** " + ", ".join(node.name for node in hubs) + "."
        )
    for community in overview[:5]:
        lines.append(
            f"\n**{community['name']}** — {community['size']} entities. {community['summary']}"
        )
    edges = context.relevant_edges(8)
    if edges:
        lines.append("\n**Strongest cross-cluster evidence:**")
        for edge in edges[:5]:
            source = node_map.get(edge.source)
            target = node_map.get(edge.target)
            lines.append(
                f"- **{source.name if source else edge.source}** {_verb(edge)} "
                f"**{target.name if target else edge.target}**{_date_suffix(edge)}. "
                f"{edge.description} [[{edge.id}]]"
            )
    return "\n".join(lines)


# --------------------------------------------------------------------------- LLM narrative
SYSTEM_PROMPT = """You are a graph intelligence analyst writing a grounded investigative brief.
Rules:
- Use ONLY the supplied facts. Never invent entities, dates or causal claims.
- Every factual sentence must end with a citation anchor in the form [[edge_id]] using the
  exact edge ids supplied. An anchor may be reused.
- Write 2-4 short markdown paragraphs. Bold entity names. No preamble, no meta commentary.
- If the facts do not answer the question, say so plainly and explain what is missing."""


def _prompt(context: SynthesisContext) -> str:
    node_map = context.node_map
    edge_map = context.edge_map
    rows: list[str] = []
    for edge in context.relevant_edges():
        source = node_map.get(edge.source)
        target = node_map.get(edge.target)
        rows.append(
            f"[{edge.id}] {source.name if source else edge.source} --{edge.type}--> "
            f"{target.name if target else edge.target} | date={edge.date or 'unknown'} | "
            f"strength={edge.strength} | source={edge.source_doc or 'seed'} "
            f"p{edge.source_page or '?'} | {edge.description}"
        )
    if context.impact:
        impact = context.impact
        rows.append(
            f"[impact] severity={impact.severity} risk={impact.risk_score} "
            f"disruption={impact.disruption_ratio} orphaned="
            f"{', '.join(node.name for node in impact.orphaned) or 'none'} "
            f"surges={', '.join(f'{s.name} +{s.delta_pct}%' for s in impact.centrality_surge[:4])}"
        )
    if context.mode == "TEMPORAL" and context.year:
        diff = temporal_diff(context.edges, context.year)
        rows.append(
            f"[temporal] year={context.year} active_edges={diff.active_edges} "
            f"new={len(diff.new_edge_ids)} dissolved={len(diff.dissolved_edge_ids)}"
        )
    return (
        f"User question: {context.query}\n"
        f"Detected intent: {context.mode}\n\n"
        f"Verified graph facts (edge_id | fact):\n" + "\n".join(rows)
    )


async def stream_narrative(context: SynthesisContext) -> AsyncIterator[str]:
    if llm.is_enabled():
        try:
            buffer: list[str] = []
            async for token in llm.stream_chat(
                system_prompt=SYSTEM_PROMPT,
                user_prompt=_prompt(context),
                max_tokens=900,
            ):
                buffer.append(token)
                yield token
            if buffer:
                return
        except Exception as exc:  # pragma: no cover - network dependent
            logger.warning("LLM narrative failed (%s) — using local synthesizer", exc)

    narrative = fallback_narrative(context)
    for chunk in _tokenize(narrative):
        yield chunk
        await asyncio.sleep(0.012)


def _tokenize(text: str, size: int = 5) -> list[str]:
    """Split on whitespace while keeping markdown/citation tokens intact."""
    words = re.split(r"(\s+)", text)
    chunks: list[str] = []
    buffer: list[str] = []
    count = 0
    for word in words:
        buffer.append(word)
        if word.strip():
            count += 1
        if count >= size:
            chunks.append("".join(buffer))
            buffer = []
            count = 0
    if buffer:
        chunks.append("".join(buffer))
    return chunks


def render_citations(text: str, context: SynthesisContext) -> str:
    """Optionally replace anchors with human labels server-side."""
    edge_map = context.edge_map

    def replace(match: re.Match[str]) -> str:
        edge = edge_map.get(match.group(1))
        if not edge:
            return ""
        return f"[{edge.source_doc or 'source'}{f' p.{edge.source_page}' if edge.source_page else ''}]"

    return CITATION_RE.sub(replace, text)
