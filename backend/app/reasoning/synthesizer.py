"""Grounded narrative synthesis with streaming tokens and citation anchors.

When an OpenAI key is configured the narrative is generated by the model from a
fact sheet of retrieved edges (each tagged with its edge id). Otherwise a
deterministic, template-driven narrator produces the same structure locally, which
keeps demo mode genuinely useful rather than a blank panel.

Citation anchors use the form ``[[edge_id]]``; the frontend resolves them to badges
that highlight the exact path on the WebGL canvas.
"""

